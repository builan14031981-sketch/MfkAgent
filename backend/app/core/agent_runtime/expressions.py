def get_expression_prompt(profile_id: str | None) -> str:
    """根据 expression_profile ID 返回对应的表达规则文本。

    Args:
        profile_id: Agent.expression_profile 字段值

    Returns:
        表达规则文本，未知 ID 或 None 时返回空串
    """
    if not profile_id:
        return ""
    return EXPRESSION_PROFILES.get(profile_id, "")
